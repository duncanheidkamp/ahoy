select setval(pg_get_serial_sequence('public.phrases', 'id'), (select max(id) from public.phrases));

-- id 1 = 'Ahoy!' is the default and must never be deleted.
alter table public.users
  add column active_phrase_id integer not null default 1
    references public.phrases(id) on delete set default;

-- Total ahoys the caller has sent.
create or replace function public.my_sent_count()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select count(*) from public.ahoys where sender_id = auth.uid();
$$;

revoke all on function public.my_sent_count() from public, anon;
grant execute on function public.my_sent_count() to authenticated;

alter table public.phrases enable row level security;

-- Secret phrases stay hidden until unlocked.
create policy "Signed-in users can view visible phrases" on public.phrases
  for select to authenticated
  using (not secret or unlock_at <= public.my_sent_count());

revoke all on table public.phrases from anon;
revoke insert, update, delete, truncate on table public.phrases from authenticated;

-- Full phrase list for a picker. Locked secret phrases are returned with their
-- text masked so the UI can show "???" without leaking the phrase.
create or replace function public.get_my_phrases()
returns table (
  id integer,
  text text,
  unlock_at integer,
  secret boolean,
  sort integer,
  unlocked boolean,
  active boolean
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_count bigint;
  v_active integer;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;
  select count(*) into v_count from public.ahoys a where a.sender_id = v_uid;
  select u.active_phrase_id into v_active from public.users u where u.id = v_uid;

  return query
    select p.id,
           case when p.secret and p.unlock_at > v_count then '???'::text else p.text end,
           p.unlock_at,
           p.secret,
           p.sort,
           p.unlock_at <= v_count,
           p.id = v_active
    from public.phrases p
    order by p.sort, p.id;
end;
$$;

revoke all on function public.get_my_phrases() from public, anon;
grant execute on function public.get_my_phrases() to authenticated;

create or replace function public.set_active_phrase(phrase_id integer)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_unlock_at integer;
  v_count bigint;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  select p.unlock_at into v_unlock_at from public.phrases p where p.id = phrase_id;
  if not found then
    raise exception 'unknown_phrase' using errcode = '22023';
  end if;

  select count(*) into v_count from public.ahoys a where a.sender_id = v_uid;
  if v_count < v_unlock_at then
    raise exception 'phrase_locked' using errcode = '42501';
  end if;

  update public.users set active_phrase_id = phrase_id where id = v_uid;
end;
$$;

revoke all on function public.set_active_phrase(integer) from public, anon;
grant execute on function public.set_active_phrase(integer) to authenticated;

-- The caller's own profile, including fields hidden from other users.
create or replace function public.get_my_profile()
returns table (
  id uuid,
  username text,
  created_at timestamptz,
  active_phrase_id integer,
  active_phrase text,
  has_fcm_token boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  select u.id, u.username, u.created_at, u.active_phrase_id, p.text, u.fcm_token is not null
  from public.users u
  join public.phrases p on p.id = u.active_phrase_id
  where u.id = auth.uid();
$$;

revoke all on function public.get_my_profile() from public, anon;
grant execute on function public.get_my_profile() to authenticated;
