-- =============================================================================
-- Server-side phrases.
--
-- Before: the phrase lived in client localStorage and the send route accepted
-- any text.
-- After: phrases are rows; each user has active_phrase_id; set_active_phrase()
-- checks the caller's sent count against unlock_at. The send path reads the
-- phrase from the database and never from the client.
--
-- NOTE: thresholds for Ope!, You betcha!, Avast!, Land ho! and Yarr, she blows!
-- are PLACEHOLDERS pending Duncan's decision. Change them in a new migration.
-- =============================================================================

create table public.phrases (
  id integer generated by default as identity primary key,
  text text not null unique,
  unlock_at integer not null default 0 check (unlock_at >= 0),
  secret boolean not null default false,
  sort integer not null default 0
);

